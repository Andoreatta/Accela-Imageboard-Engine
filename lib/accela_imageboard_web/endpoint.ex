defmodule AccelaImageboardWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :accela_imageboard

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  #
  # Hardening:
  #   * `http_only: true` keeps the cookie away from JavaScript (XSS can still
  #     act as the user, but cannot exfiltrate the session);
  #   * `same_site: "Lax"` blocks cross-site POSTs riding on the cookie (CSRF
  #     defence in depth, on top of Phoenix's CSRF token);
  #   * `secure: true` keeps the cookie off plain-http requests at all.
  #
  # `:session_cookie_secure` is a *compile-time* flag: Plug.Session options are
  # baked into the endpoint when it is compiled, so it must be set when the
  # release is built. config/dev.exs disables it for http://localhost;
  # config/prod.exs keeps it on and config/runtime.exs refuses to boot a prod
  # node that tries to disable it.
  @session_options [
    store: :cookie,
    key: "_accela_imageboard_key",
    signing_salt: "Uot+Ee/z",
    same_site: "Lax",
    http_only: true,
    secure: Application.compile_env(:accela_imageboard, :session_cookie_secure, true)
  ]

  # `:peer_data` (the connection's address) and `:x_headers` (only believed when the
  # peer is a trusted proxy, see AccelaImageboardWeb.ClientIp) let a LiveView compute
  # the anonymous poster identity at mount without trusting anything from params.
  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [:peer_data, :x_headers, session: @session_options]],
    longpoll: [connect_info: [:peer_data, :x_headers, session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :accela_imageboard,
    gzip: not code_reloading?,
    only: AccelaImageboardWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :accela_imageboard
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # Regular form posts are tiny (a reply body is at most 10 kB), and image uploads
  # do not travel through this parser at all: LiveView sends them over its own
  # upload endpoint, so `allow_upload(max_file_size:)` and
  # `AccelaImageboard.Media.Validation` are what bound an upload. Keeping the global
  # body limit small means an attacker cannot make every route buffer megabytes
  # (audit F15).
  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    length: 1_000_000,
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug AccelaImageboardWeb.Router
end
